#!/usr/bin/env bash
# Refresh the OCE Konflux pins after an upstream sync and propose them in one
# pull request. .github/workflows/konflux-oce-pins-refresh.yml runs this from
# the repository root, on main with full history, with a GH_TOKEN that can push
# branches, open pull requests and dispatch workflows.
#
# Every sync moves OCE_UPSTREAM_COMMIT, so the pull request changes both
# build-args files and its merge starts both Konflux on-push builds. When
# oce_pins.py --check still fails afterwards, an upstream recipe change needs a
# manual port, and the pull request stays a draft with the check output.
set -euo pipefail

branch=konflux/oce-pins-refresh
confs=(deploy/konflux/oce-runtime/build-args.conf deploy/konflux/oce-controller/build-args.conf)
workflow=.github/workflows/konflux-oce-pins-refresh.yml

main=$(git rev-parse HEAD)
upstream=$(git log --first-parent --merges -1 --format=%P \
    --grep="^Merge remote-tracking branch 'upstream/main'" HEAD | cut -d' ' -f2)
if ! [[ $upstream =~ ^[0-9a-f]{40}$ ]]; then
    echo "ERROR: no upstream sync merge on the first-parent history of ${main}" >&2
    exit 1
fi

# A recipe the pins extractor can no longer read fails the refresh before it
# writes anything. Carry on so --check reports the error in a draft pull request.
if ! python3 deploy/konflux/oce_pins.py; then
    echo "WARNING: the pins refresh failed; the draft pull request carries the --check output" >&2
fi
for conf in "${confs[@]}"; do
    if ! grep -q '^OCE_UPSTREAM_COMMIT=' "$conf"; then
        echo "ERROR: ${conf} has no OCE_UPSTREAM_COMMIT line" >&2
        exit 1
    fi
    sed -i "s/^OCE_UPSTREAM_COMMIT=.*/OCE_UPSTREAM_COMMIT=${upstream}/" "$conf"
done

existing=$(gh pr list --head "$branch" --base main --state open --json number --jq '.[0].number // empty')

if git diff --quiet; then
    echo "main ${main} already has the pins for upstream ${upstream}"
    if [[ -n $existing ]]; then
        gh pr close "$existing" --delete-branch --comment "main ${main} already has the pins for upstream ${upstream}."
    fi
    exit 0
fi

check_ok=true
report=$(python3 deploy/konflux/oce_pins.py --check 2>&1) || check_ok=false
# Drop the download progress lines from the report.
report=$(grep -v '^  fetching ' <<< "$report" || true)
printf '%s\n' "$report"

title="CARRY: RHAI-57800: Refresh the OCE Konflux pins for upstream ${upstream:0:9}"
# Pass the bot identity to this commit only, so a local run leaves the clone's
# configuration alone.
bot=(-c 'user.name=github-actions[bot]' -c 'user.email=41898282+github-actions[bot]@users.noreply.github.com')
git checkout -q -B "$branch"
git "${bot[@]}" commit -q -s -m "$title" -m "Generated by ${workflow} on main ${main:0:9}." -- "${confs[@]}"
git push -q --force origin "$branch"

body=$(mktemp)
{
    echo "Refreshes the derived OCE Konflux pins on main ${main} and records upstream ${upstream}, so merging this rebuilds both OCE images."
    echo
    if $check_ok; then
        echo '`deploy/konflux/oce_pins.py --check` passes on this branch.'
    else
        echo '`deploy/konflux/oce_pins.py --check` still fails, so an upstream recipe change needs a manual port. Port it in a separate pull request, reading the whole diff below before running `--ported`. This pull request closes itself once main has the pins.'
        echo
        echo '```'
        # Stay well under the 65536 character limit for pull request bodies.
        printf '%s\n' "${report:0:60000}"
        echo '```'
    fi
    echo
    echo "${workflow} replaces this branch after every push to main, so do not push to it."
} > "$body"

if [[ -z $existing ]]; then
    draft=()
    $check_ok || draft=(--draft)
    gh pr create --base main --head "$branch" --title "$title" --body-file "$body" "${draft[@]}"
else
    gh pr edit "$existing" --title "$title" --body-file "$body"
    is_draft=$(gh pr view "$existing" --json isDraft --jq .isDraft)
    if $check_ok && [[ $is_draft == true ]]; then
        gh pr ready "$existing"
    elif ! $check_ok && [[ $is_draft == false ]]; then
        gh pr ready --undo "$existing"
    fi
fi

# Pushes made with the workflow token start no workflows, but dispatches do, so
# run the pins check on the branch to report it on the pull request.
gh workflow run konflux-oce-pins.yml --ref "$branch"
